"""Pruebas automáticas de la HU-006 (validación del archivo) y la HU-005 (importación)."""

import pytest
from sqlalchemy import func, select

from app.models import Importacion, Medicion

# --- Archivos de ejemplo ---------------------------------------------------

LIBREVIEW = """Glucose Data,Generated on,10-20-2026 21:02 UTC,Generated by,Usuario de prueba
Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Notes
FreeStyle LibreLink,SIM-0001,10-15-2026 12:00,0,128,,
FreeStyle LibreLink,SIM-0001,10-15-2026 12:15,0,LO,,
FreeStyle LibreLink,SIM-0001,10-15-2026 12:30,0,136,,
FreeStyle LibreLink,SIM-0001,10-15-2026 12:30,1,,150,
FreeStyle LibreLink,SIM-0001,10-15-2026 12:52,1,,138,
FreeStyle LibreLink,SIM-0001,10-15-2026 13:00,6,,,una nota
"""

DEXCOM = """Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Patient Info,Device Info,Source Device ID,Glucose Value (mg/dL)
1,,FirstName,,Prueba,,,
2,,Device,,,G7,SIM-0002,
3,,Alert,Low,,,,55
4,2026-10-15T12:30:00,EGV,,,,SIM-0002,136
5,2026-10-15T12:35:00,EGV,,,,SIM-0002,High
6,2026-10-15T12:40:00,EGV,,,,SIM-0002,135
"""

DEXCOM_MMOL = DEXCOM.replace("(mg/dL)", "(mmol/L)").replace(",136", ",7.5").replace(",135", ",8")


def generico(filas: list[str], separador=",") -> str:
    return f"fecha_hora{separador}glucosa_mg_dl\n" + "\n".join(filas) + "\n"


def diez_filas_validas(dia="2026-10-15") -> list[str]:
    return [f"{dia} 10:{m:02d},{100 + m}" for m in range(0, 50, 5)]


@pytest.fixture
def sesion(cliente):
    """Un cliente con una cuenta creada y la sesión iniciada."""
    cuenta = {"email": "nara@example.com", "contrasena": "Glucosa2026", "acepta_consentimiento": True}
    cliente.post("/auth/registro", json=cuenta)
    cliente.post("/auth/login", json={"email": cuenta["email"], "contrasena": cuenta["contrasena"]})
    return cliente


def validar(cliente, texto: str, nombre="mediciones.csv", formato_fecha=None):
    datos = {"formato_fecha": formato_fecha} if formato_fecha else {}
    return cliente.post("/importaciones/validar", files={"archivo": (nombre, texto.encode(), "text/csv")}, data=datos)


def importar(cliente, texto: str, nombre="mediciones.csv", formato_fecha=None):
    datos = {"formato_fecha": formato_fecha} if formato_fecha else {}
    return cliente.post("/importaciones", files={"archivo": (nombre, texto.encode(), "text/csv")}, data=datos)


def cantidad_mediciones(db) -> int:
    return db.scalar(select(func.count()).select_from(Medicion))


# --- Adaptadores (Anexo I) --------------------------------------------------

def test_libreview_usa_historial_y_escaneos_sin_historial(sesion, db):
    r = validar(sesion, LIBREVIEW, formato_fecha="mes-dia").json()
    assert r["aceptado"] and r["formato"] == "LibreView"
    # 3 históricos + 1 escaneo (12:52). El escaneo de 12:30 se descarta: ya hay histórico.
    assert r["mediciones_nuevas"] == 4
    importar(sesion, LIBREVIEW, formato_fecha="mes-dia")
    marcas = dict(db.execute(select(Medicion.valor, Medicion.marca)).all())
    assert marcas[40] == "bajo"  # «LO» se conserva con su marca


def test_dexcom_toma_solo_egv_y_marca_high(sesion, db):
    r = validar(sesion, DEXCOM).json()
    assert r["aceptado"] and r["formato"] == "Dexcom Clarity"
    assert r["mediciones_nuevas"] == 3 and r["filas_invalidas"] == 0
    importar(sesion, DEXCOM)
    assert db.scalar(select(Medicion.marca).where(Medicion.valor == 400)) == "alto"


def test_dexcom_en_mmol_se_convierte_a_mg_dl(sesion, db):
    importar(sesion, DEXCOM_MMOL)
    valores = set(db.scalars(select(Medicion.valor)))
    assert {135, 144} <= valores  # 7,5 × 18,016 ≈ 135 ; 8 × 18,016 ≈ 144


def test_generico_con_punto_y_coma(sesion):
    r = validar(sesion, generico([f.replace(",", ";") for f in diez_filas_validas()], ";")).json()
    assert r["aceptado"] and r["mediciones_nuevas"] == 10


def test_horas_se_interpretan_en_la_zona_del_usuario(sesion, db):
    importar(sesion, generico(["2026-10-15 12:00,120"]))
    # 12:00 en Buenos Aires (UTC-3) son las 15:00 UTC.
    guardada = db.scalar(select(Medicion.fecha_hora))
    assert guardada.hour == 15


# --- Formato regional de fecha (corrección del director a la HU-006) --------

LIBRE_AMBIGUO = LIBREVIEW.replace("10-15-2026", "09-10-2026")  # 9 de octubre o 10 de septiembre


def test_libreview_sin_formato_confirmado_pide_elegir(sesion, db):
    r = validar(sesion, LIBRE_AMBIGUO).json()
    assert not r["aceptado"] and r["requiere_formato_fecha"]
    opciones = {o["id"]: o for o in r["opciones_formato_fecha"]}
    assert "10 de septiembre" in opciones["mes-dia"]["ejemplo"]
    assert "9 de octubre" in opciones["dia-mes"]["ejemplo"]
    # No se guarda nada ni se registra como rechazo: falta una confirmación.
    assert db.scalar(select(func.count()).select_from(Importacion)) == 0
    assert importar(sesion, LIBRE_AMBIGUO).status_code == 422


def test_la_variante_confirmada_define_la_fecha(sesion, db):
    importar(sesion, LIBRE_AMBIGUO, formato_fecha="dia-mes")
    dias = sesion.get("/mediciones/dias").json()
    assert dias[0]["fecha"] == "2026-10-09"


def test_cada_importacion_guarda_formato_y_zona(sesion):
    importar(sesion, LIBREVIEW, formato_fecha="mes-dia")
    importar(sesion, DEXCOM)
    lista = sesion.get("/importaciones").json()
    assert {(i["formato"], i["formato_fecha"]) for i in lista} == {
        ("LibreView", "mes-dia"), ("Dexcom Clarity", "%Y-%m-%dT%H:%M:%S")}
    assert all(i["zona_horaria"] == "America/Argentina/Buenos_Aires" for i in lista)


def test_formato_equivocado_sugiere_el_otro(sesion):
    filas = "\n".join(f"FreeStyle LibreLink,SIM-0001,10-{d:02d}-2026 12:00,0,120,," for d in range(13, 23))
    texto = LIBREVIEW.split("FreeStyle")[0] + filas + "\n"
    r = validar(sesion, texto, formato_fecha="dia-mes").json()
    assert not r["aceptado"] and "probá con el otro formato" in r["motivo_rechazo"]


def test_fechas_que_no_corresponden_a_la_variante_son_invalidas(sesion):
    # «10-15-2026» no existe como día-mes (no hay mes 15): esas filas quedan inválidas.
    r = validar(sesion, LIBREVIEW, formato_fecha="dia-mes").json()
    assert r["filas_invalidas"] > 0


# --- HU-006, criterio 1: archivos rechazados --------------------------------

def test_extension_distinta_de_csv(sesion):
    r = validar(sesion, generico(diez_filas_validas()), nombre="datos.xlsx").json()
